"""config.py — все параметры одного прогона в одном плоском dataclass.

Величины безразмерные (как в ``fix_base2.py``): E, h, q0, a, Delta подобраны так,
чтобы прогиб и реакция были порядка единицы. Жёсткость ``D`` — производная
величина (свойство). Ничего «магического» ниже по стеку: всё берётся отсюда.

Обозначения:
    E, nu, h — упругие постоянные и толщина;
    D        — цилиндрическая жёсткость, D = E·h³ / (12·(1 − ν²));
    q0       — равномерная поперечная нагрузка (q0 > 0 «вниз», w > 0 «вниз»);
    a        — радиус круга (постановка верификации 1D↔2D);
    Delta    — зазор до жёсткого основания (контакт, МОР);
    beta     — БЕЗРАЗМЕРНЫЙ коэффициент релаксации МОР: в ContactMOR шаг
               нормируется на усиление оператора, β_eff = β/gain, поэтому
               условие сходимости (теорема 4) имеет вид 0 < β < 2;
    p        — степень Чебышёва по каждой оси (N = (p+1)² базисных функций);
    Q        — число узлов квадратуры Гаусса–Лежандра по каждой оси;
    grid_n   — сетка для реакции/сэмплинга w и визуализации.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class Config:
    # физика (безразмерно, как в fix_base2.py)
    E: float = 2.1e6
    nu: float = 0.3
    h: float = 1.0
    q0: float = 4.0          # равномерная нагрузка
    # геометрия
    a: float = 1.0           # радиус круга (для верификации)
    # контакт
    Delta: float = 1.0       # зазор до жёсткого основания
    beta: float = 1.2        # релаксация МОР, безразмерная (теорема 4: 0 < β < 2)
    max_iter: int = 20000    # итерации МОР
    tol: float = 1e-8        # порог критерия остановки (см. stop)
    stop: str = "dr"         # критерий: "dr" — ‖r_k−r_{k−1}‖ < tol (абсолютный, прежний);
    #                          "comp" — безразмерная KKT-невязка Синьорини < tol
    #                          (см. ContactMOR.solve)
    # дискретизация
    p: int = 12              # степень Чебышёва по каждой оси (N = (p+1)^2)
    Q: int = 64              # число узлов квадратуры по каждой оси
    grid_n: int = 80         # сетка для реакции/сэмплинга w и визуализации
    # геометрическая нелинейность (теория Кармана, membrane.py) --------------- #
    # Итерация Пикара по замороженным мембранным усилиям N_k (KarmanPlate):
    #   w_{k+1} = (1−θ)·w_k + θ·T(w_k),  θ = karman_relax (недорелаксация);
    #   останов ‖w_{k+1}−w_k‖_{L2} / ‖w_{k+1}‖ < karman_tol.
    # Большие прогибы достигаются НАРАЩИВАНИЕМ нагрузки за n_load_steps шагов
    # (тёплый старт каждого уровня предыдущим решением).
    n_load_steps: int = 1        # число шагов по нагрузке (1 — при малой нагрузке)
    karman_tol: float = 1e-8     # относительный порог останова Пикара по ‖Δw‖
    karman_max_iter: int = 200   # предел итераций Пикара на один уровень нагрузки
    karman_relax: float = 1.0    # недорелаксация θ ∈ (0, 1] (1 — без релаксации)
    karman_method: str = "picard"  # "picard" (по умолч.) | "newton" (ускоритель)
    # полная нелинейная КТН (theory=ktn_full, ktn_full.py) — переиспользует
    # параметры итерации Кармана выше; собственный выбор метода:
    ktn_method: str = "picard"   # "picard" (по умолч.) | "newton" (ускоритель)
    # нелинейный контакт МОР+КТН (contact_nl.py, v0.6.0): схема композиции двух
    # итераций (§4.2) — "merged" (совмещённый, рабочий, быстрый; предмет T7) или
    # "nested" (вложенный, эталон корректности, дорогой).
    contact_scheme: str = "merged"
    # нормировка усиления оператора нелинейного контакта (теорема 4, §4.1):
    # "secant" — секущая податливость свободного нелинейного решения (быстрее,
    # но при сильном мембранном ужесточении может нарушить условие сжатия);
    # "linear" — линейная податливость (верхняя грань ‖G‖ ⇒ сходимость
    # гарантирована, итераций больше). См. contact_nl.NonlinearContactMOR.
    contact_gain: str = "secant"
    # ускорение Андерсона ВНЕШНЕГО цикла МОР (contact_nl.py, v0.6.4): окно памяти
    # проекционного Андерсона по реакции r; 0 — выключено (чистый проекционный
    # фиксированный шаг, поведение по умолчанию число-в-число). >0 — ускоряет
    # сходимость реакции (меньше дорогих внутренних нелинейных решений) при ТОЙ ЖЕ
    # неподвижной точке. Проекция r ≥ 0 применяется ПОСЛЕ смешения (§4.1).
    mor_anderson: int = 0
    # упругое (двустороннее) основание Винклера (v0.6.6): D·Δ²w + k_w·w = q;
    # 0 — без основания (прежнее поведение бит-точно). Свёртывается в изгибную
    # жёсткость (+k_w∫ψψ) ⇒ работает во всех трактах (нелинейные, eigen, контакт).
    winkler: float = 0.0
    # точечные упругие опоры (v0.7.0): энергия (k/2)·Σ_j w(P_j)² — ранг-1
    # добавки k·ψ(P_j)ψ(P_j)^T к жёсткости ДО факторизации (паттерн Винклера).
    # () — без опор (прежнее поведение бит-точно). Жёсткая опора — штраф
    # k ≈ 1e6·D/a³ (ошибка штрафа ~5e-5, закон 1/(1+k·G_N)).
    supports_points: tuple = ()      # пары (x, y)
    supports_stiffness: float = 0.0  # жёсткость k каждой пружины (> 0)
    # ортотропия классической теории (v0.7.0): жёсткости (D11, D12, D22, D66)
    # энергии U = ½∫[D11 w_xx² + 2D12 w_xx w_yy + D22 w_yy² + 4D66 w_xy²];
    # None — изотропный путь бит-точно (свойство D ниже не используется
    # ортотропной веткой: решатели берут D_ref = D11 из кортежа).
    ortho_D: tuple | None = None
    # ортотропная МЕМБРАННАЯ жёсткость (v0.7.0, только theory=karman):
    # (A11, A12, A22, A66) закона N = A·ε плоского напряжённого состояния;
    # вычисляется из ИНЖЕНЕРНОГО набора (Ex, Ey, nu_xy, Gxy) + h в to_config
    # (прямой D-ввод для Кармана отклоняется — A неопределима). None — прежний
    # изотропный путь бит-точно.
    ortho_A: tuple | None = None
    # переменная толщина h(x, y) (v0.7.0): строка-выражение (белый список
    # exprfield); D(x,y) = E·h³/12(1−ν²) входит ВЕСОМ полной билинейной формы
    # (при D≠const гауссов член НЕ нуль-лагранжиан — упрощённый ∫DΔψΔψ неверен).
    # None — прежний путь бит-точно; поле h выше при h_expr — только
    # нормировка D0 (аналитически сокращается).
    h_expr: str | None = None
    # термоизгиб (v0.7.0): константный термомомент M_T (Н·м/м) по толщине —
    # D·Δ²w = q − ΔM_T; конвенция M_T = αEΔT·h²/(12(1−ν)) для линейного
    # перепада ΔT (множитель 1/(1−ν) уже включён). 0 — прежний путь бит-точно.
    # Защемление НЕ гнётся константным M_T (w ≡ 0), сдвигаются лишь моменты.
    thermal_moment: float = 0.0

    @property
    def D(self) -> float:
        return self.E * self.h**3 / (12 * (1 - self.nu**2))


__all__ = ["Config"]
